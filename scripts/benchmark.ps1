# Load-test the site and append a row to benchmarks/results.md.
# Usage:  powershell -ExecutionPolicy Bypass -File scripts\benchmark.ps1 -Label "no cache"
#         -Url https://restaurant.example.com  to test through Cloudflare instead of Nginx directly
#         -Bypass  to skip the page cache and load the PHP backends
param(
    [Parameter(Mandatory)] [string]$Label,
    [string]$Url = 'http://nginx',
    [int]$Vus = 20,
    [string]$Duration = '30s',
    [switch]$Bypass  # skip the page cache (measure PHP capacity)
)
$ErrorActionPreference = 'Stop'
Set-Location (Split-Path $PSScriptRoot -Parent)

$envVars = @{}
Get-Content .env | Where-Object { $_ -match '^\w+=' } | ForEach-Object { $k, $v = $_ -split '=', 2; $envVars[$k] = $v }
$slug = ($Label -replace '[^\w]+', '-').Trim('-').ToLower()
$bypassFlag = if ($Bypass) { '1' } else { '0' }
$hostHeader = if ($Url -eq 'http://nginx') { ([uri]$envVars.SITE_URL).Authority } else { '' }

function Get-DbQuestions {
    $out = docker compose exec -T db mariadb -uroot "-p$($envVars.DB_ROOT_PASSWORD)" -N -e "SHOW GLOBAL STATUS LIKE 'Questions'"
    [long]($out -split '\s+')[1]
}

Write-Host "==> Warming up" -ForegroundColor Cyan
docker compose run --rm -q -e BASE_URL=$Url -e HOST_HEADER=$hostHeader -e BYPASS=$bypassFlag -e VUS=5 -e DURATION=5s k6 run -q /bench/load.js | Out-Null

function Get-RedisStats {
    $info = docker compose exec -T redis redis-cli info stats
    $h = [long](($info | Select-String 'keyspace_hits:(\d+)').Matches.Groups[1].Value)
    $m = [long](($info | Select-String 'keyspace_misses:(\d+)').Matches.Groups[1].Value)
    @{ Hits = $h; Misses = $m }
}

Write-Host "==> $Label : $Vus virtual users for $Duration against $Url" -ForegroundColor Cyan
$q0 = Get-DbQuestions
$r0 = Get-RedisStats
docker compose run --rm -q -e BASE_URL=$Url -e HOST_HEADER=$hostHeader -e BYPASS=$bypassFlag -e VUS=$Vus -e DURATION=$Duration k6 `
    run -q --summary-export=/bench/raw/$slug.json /bench/load.js
if ($LASTEXITCODE) { throw 'k6 failed' }
$q1 = Get-DbQuestions
$r1 = Get-RedisStats

$s    = Get-Content "benchmarks/raw/$slug.json" | ConvertFrom-Json
$reqs = $s.metrics.http_reqs.count
$d    = $s.metrics.http_req_duration
$fail = [math]::Round($s.metrics.http_req_failed.value * 100, 2)
$qpr  = if ($reqs) { [math]::Round(($q1 - $q0) / $reqs, 1) } else { 0 }
$rh   = $r1.Hits - $r0.Hits
$rm   = $r1.Misses - $r0.Misses
$rhit = if ($rh + $rm) { '{0:N1}%' -f (100 * $rh / ($rh + $rm)) } else { '-' }
$row  = '| {0} | {1} | {2:N0} | {3:N1} | {4:N1} | {5:N1} | {6}% | {7} | {8} |' -f $Label, $Vus, $s.metrics.http_reqs.rate, $d.med, $d.'p(95)', $d.'p(99)', $fail, $qpr, $rhit

if (-not (Test-Path benchmarks/results.md)) {
    @(
        '# Benchmark results', '',
        'Generated by `scripts/benchmark-suite.ps1`. Latency in milliseconds.',
        '"DB q/req" = MariaDB queries per request. "Redis hits" = object-cache hit rate during the run.', '',
        'Machine: Windows + Docker Desktop (WSL2 backend, 12 CPUs, 8 GB). k6 runs in a container on the',
        'same Docker network and hits Nginx directly. Everything shares one machine, so expect roughly',
        '+-20% run-to-run variation: compare rows by order of magnitude, not by the last digit.', '',
        '| Configuration | VUs | Req/s | p50 | p95 | p99 | Errors | DB q/req | Redis hits |',
        '|---|---|---|---|---|---|---|---|---|'
    ) -join "`n" | Set-Content benchmarks/results.md -NoNewline
}
# UTF-8 without BOM (Windows PowerShell 5's -Encoding utf8 adds one)
[IO.File]::AppendAllText("$PWD/benchmarks/results.md", "`n$row", (New-Object Text.UTF8Encoding $false))
Write-Host $row -ForegroundColor Green
